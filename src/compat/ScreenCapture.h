#pragma once

// ============================================================================
//  ScreenCapture.h —— 抓取"当前屏幕的显示"
// ----------------------------------------------------------------------------
//  ★ 本文件与 GlobalHotkey 是本工程**唯一允许出现平台判断**（`#if defined(Q_OS_WIN)`）
//    的地方 ★
//    与 QtCompat.h 把 `#if QT_VERSION` 收在 src/compat/ 是同一条约定：
//    环境相关的判断集中到一个目录，将来换 Qt 版本或换平台只需看这里。
//    其余任何代码一律只依赖本文件给出的**契约**，不写 `#if`。
//
//  ★ 为什么"抓屏幕"也算 compat 的事 ★
//    QScreen::grabWindow() 的语义随平台而变：Windows 上对 `window == 0`
//    的处理、Wayland 上常常直接失败、离屏平台（自检用的 offscreen）上
//    根本没有真实屏幕可抓。把这些差异包进一个函数之后，上层
//    （MainWindow）只需依赖一个简单的契约 —— 见下。
// ============================================================================

#include <QImage>
#include <QString>

namespace zl {

// 抓取"用户此刻正在看的那块屏幕"，返回一张**可直接当图层用**的图像。
//
// ── 契约（三条，改实现时必须保持）────────────────────────────────────
//
//  ① **设备像素**：按真实像素点给出。150% 缩放的 1920×1080 屏幕返回
//     2880×1620，不做任何缩放、不降到逻辑尺寸。
//     理由：这是图像编辑器 —— 用户要的是"屏幕上那些像素"，不是"逻辑尺寸"。
//     降采样过一次的截图无法还原。
//
//  ② **devicePixelRatio 归一为 1.0**：Qt 会把抓回来的 QPixmap 标成 dpr=2
//     之类的元信息（那是给绘制用的）。图层的像素缓冲不认这个 ——
//     Layer 的铁律是 ARGB32_Premultiplied + 一像素一个像素。
//     标成 1.0 之后，"1 个图像像素 = 画布上的 1 个像素"才成立，
//     另存出来的文件尺寸也才等于屏幕上一眼量到的尺寸。
//
//  ③ **失败返回空 QImage**：没有屏幕、平台拒绝、会话被锁……一律返回空图。
//     不抛异常、不弹框、不写日志刷屏 —— 由调用方拿 isNull() 决定怎么报。
//     （★ 自动化的第一原则：不能把一个"环境不支持"变成一次挂死。）
//
// ── 取哪一块屏幕 ──────────────────────────────────────────────────────
//
//   优先取**鼠标光标所在**的那一块，取不到再回落主屏。
//   多显示器时，用户按下快捷键那一刻光标停在哪块屏上，他想截的就是哪块 ——
//   这比"永远主屏"准确得多（否则副屏上的用户每次都要手工挪窗口）。
//
//   ★ 不做"所有屏幕拼成一张" ★
//     各屏的 dpr 可能不同，拼图要逐屏换算并给矮的那块补黑边，
//     代价与收益不成比例；真要整块虚拟桌面，系统自带的截图工具更合适。
// ── "抓不到"的分类（供上层组织**可操作**的提示）──────────────────────
//
//  契约③让失败表现为一张空图 —— 对上层是最省事的接口，但对用户是无声的。
//  上层需要知道"这次失败是不是因为**整个会话根本不允许抓**"，才能给出
//  "那你该怎么办"的建议，而不是一句"截图失败"。
//
//  Wayland 就是这种情形：合成器不允许客户端读屏幕上不属于自己的像素，
//  Qt 的 grabWindow() 在那里**恒返回空图**（不是偶发失败，是这条路不通）。
enum class CaptureBlock {
    None,      // 不是已知的平台限制（可能是锁屏、没有显示器……）
    Wayland,   // Wayland 会话：合成器不允许应用直接读屏幕像素
};

// 当前会话是否会整体阻止抓屏。与本次 grabScreen() 成没成无关 ——
// 它只回答"这个环境有没有一道过不去的墙"。
//
//  ★ 实现里不写 `#if defined(Q_OS_LINUX)` ★
//    看平台名就够：名字里带 "wayland" 才是 Wayland 会话，在 Windows /
//    macOS 上这个条件天然为假。少一个 `#if`，就少一处"换平台忘了改"。
CaptureBlock screenCaptureBlock();

// ---------------------------------------------------------------------------
//  Wayland：走 xdg-desktop-portal 抓屏
// ---------------------------------------------------------------------------
//  合成器不允许客户端读屏幕上不属于自己的像素，`grabWindow()` 在 Wayland 上
//  恒失败 —— 这是设计，不是缺陷。官方给的唯一正路是桌面门户
//  （org.freedesktop.portal.Screenshot）：由合成器自己截，把图写到
//  $XDG_RUNTIME_DIR 下一个临时文件，再把 file:// URI 回给我们。
//
//  ★ 这条路的三个"必须照做"，缺一个就会失效 ★
//    ① **先订阅再调用**：portal 先返回一个 request handle，结果是以
//       Response 信号回来的。non-interactive 截图可能在我们拿到 handle
//       之前就已经回完 —— 后订阅就永远等不到（见铁律第九章）。
//    ② **结果是个临时文件，读走即删**：留在 $XDG_RUNTIME_DIR 里会一直堆积。
//    ③ **必须有超时**：部分桌面会插入一次授权对话框，用户不点就永远没有
//       Response。没有超时的同步等待会把界面焊死。
//
//  拿不到图（没有门户、用户拒绝、超时、文件读不出来）一律返回空图，
//  与 grabScreen() 的契约③一致。
bool  screenCapturePortalAvailable();
QImage grabScreenViaPortal();

// 本次抓屏**是否会走**桌面门户（= Wayland 会话 且 门户可用）。
//
// ★ 与 screenCapturePortalAvailable() 分开是有原因的 ★
//   后者只回答"这台机器上有没有门户" —— 在 X11 桌面上它同样可能是 true
//   （很多发行版默认就装着 portal）。上层要的是"我这一次会不会走进
//   那条会阻塞、会弹授权框的路"，所以必须把会话类型一起算进来。
//   有了这一个函数，上层就不必自己写 `platformName().contains("wayland")`
//   —— 平台判断继续留在 compat 里。
bool screenCaptureUsesPortal();

// 上一次 grabScreen() 失败的**具体**原因（可以直接给用户看）。
// 空字符串 = 没有额外信息，调用方用通用文案即可。
//
// ★ 为什么需要它 ★
//   门户这条路的失败有好几种完全不同的含义：用户点了"拒绝"、
//   等太久没人应答、后端返回了图但文件读不出来。压成一句通用的
//   "截图失败"，用户唯一能做的就是反复重试 —— 而重试对"被拒绝"
//   是没有意义的。
QString screenCaptureLastFailure();

QImage grabScreen();


} // namespace zl
