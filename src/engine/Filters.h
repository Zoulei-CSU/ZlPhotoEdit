#pragma once

// ============================================================================
//  Filters.h —— 滤镜
// ----------------------------------------------------------------------------
//  与 Adjust.h 的区别：
//    Adjust  —— 逐像素映射。输出的每个像素只取决于输入的同一位置像素。
//                因此可以用 256 项 LUT 把成本压到极低。
//    Filters —— 邻域运算。输出的每个像素取决于输入的一个邻域
//                （模糊要采样周围，锐化要采样周围，卷积类滤镜都属此类）。
//                无法用 LUT 优化，必须老老实实逐像素算，因此性能是重点。
// ============================================================================

#include "core/ImageTypes.h"

#include <QImage>

namespace zl {
namespace filters {

// ---------------------------------------------------------------------------
//  去色 / 反色 / 阈值（这三个其实是逐像素的，放在这里只是归类方便）
// ---------------------------------------------------------------------------

// 去色：转灰度。用感知亮度权重，而不是简单的 (R+G+B)/3。
//
// 为什么不用算术平均：人眼对绿色最敏感，用算术平均会让绿色系物体
// （草地、树叶）变成一团偏暗的灰，看起来"脏"。用 Rec.601 权重后
// 亮度关系才符合视觉感受。
QImage grayscale(const QImage &src);

// 反色（负片）：out = 255 - in
//
// 实现提醒：这个操作用 applyLutRgb 实现最省事，且自动获得预乘往返的正确性。
QImage invert(const QImage &src);

// 阈值：二值化。大于 threshold 的变白，否则变黑。
// threshold 范围 0~255。
QImage threshold(const QImage &src, int threshold);

// ---------------------------------------------------------------------------
//  风格滤镜
// ---------------------------------------------------------------------------

// 怀旧（Sepia）：模拟老照片的棕黄色调。
//
// 实现是一组固定的通道混合系数，等效于一条 3×3 矩阵。
// 系数来自经典的棕褐色调公式，直接给出结果比用饱和度+色相组合更可控
// （后者在不同亮度下的表现会飘）。
QImage sepia(const QImage &src);

// 浮雕（Emboss）：基于方向性差分，产生立体感。
//
// 注意：这个滤镜会把图像整体灰度化并叠加差分结果，
// 结果图是灰底加亮暗边，与 Photoshop 的"浮雕效果"一致。
//
// strength 控制浮雕强度（0.0~3.0），directionDeg 控制光照方向。
QImage emboss(const QImage &src, qreal strength = 1.0, qreal directionDeg = 135.0);

// ---------------------------------------------------------------------------
//  模糊
// ---------------------------------------------------------------------------

// 高斯模糊。
//
// ★ 关键实现选择：分离式两遍一维卷积 ★
//   二维高斯核在半径 r 时需要 (2r+1)² 次采样。半径 10 就是 441 次。
//   而高斯核是**可分离**的（G(x,y) = G(x)·G(y)），拆成水平一遍 + 垂直一遍后
//   只需 2(2r+1) 次 —— 半径 10 时从 441 降到 42，快了一个数量级。
//
// ★ 半径换 sigma ★
//   界面上的"半径"滑块是像素值，内核需要的是 sigma。
//   换算关系：sigma ≈ radius / 3。这个 3 的来源是"3σ 覆盖 99.7% 的能量"，
//   也就是说半径为 r 的高斯核，其有效影响范围基本就是 3σ。
//   直接令 sigma = radius 会让模糊效果过强，与用户的直觉不符。
QImage gaussianBlur(const QImage &src, qreal radius);

// 方框模糊（Box Blur）。
//
// 为什么需要它：方框模糊可以用"滑动窗口求和"实现，复杂度与半径**无关**
// （O(1) per pixel，即 O(n) 总量）。而可分离高斯模糊的复杂度是 O(n·r)。
// 大半径时方框模糊快得多。
//
// 而且连续做三次方框模糊可以很好地逼近高斯模糊（中心极限定理），
// 这是很多图形库的实际做法。本工程的高斯模糊在大半径时可以选择走这条路。
QImage boxBlur(const QImage &src, int radius);

// 三次方框模糊 ≈ 高斯模糊。大半径时用它代替真正的卷积。
QImage tripleBoxBlur(const QImage &src, int radius);

// ---------------------------------------------------------------------------
//  选区蒙版专用：羽化（★ 单通道，与上面那些彩色滤镜不共用路径 ★）
// ---------------------------------------------------------------------------
//
// 输入输出都是 Format_Grayscale8 的选区蒙版。
//
// ★ 为什么不直接复用上面的 boxBlur / gaussianBlur ★
//   那两个函数内部先把图像转成 ARGB32_Premultiplied 再逐像素用 QRgb 处理 ——
//   这是"彩色图像"的模型。喂一份灰度蒙版进去会经历：
//     灰度 → ARGB32（内存 ×4）→ 模糊 → 再转回灰度
//   两次格式转换 + 4 倍内存，而蒙版本身就是十几 MB 的量级
//   （4000×3000 灰度 = 12MB，转成 ARGB32 就是 48MB）。
//   单通道版本直接操作灰度字节，既省内存也省两次全图转换。
//
// 实现用三次盒式模糊逼近高斯（中心极限定理），与 Selection::feather
// 原先内联的实现一致 —— 提取到这里是为了让"先羽化、再合入选区"的
// 调用方（选区工具）能复用同一份逻辑，而不是把七十行模糊代码抄一遍。
QImage featherGrayMask(const QImage &grayMask, qreal radius);

// ---------------------------------------------------------------------------
//  锐化
// ---------------------------------------------------------------------------

// USM 锐化（Unsharp Mask）。
//
// 原理：原图 减去 模糊图 = 高频细节；把细节按强度加回原图。
//     out = original + amount * (original - blurred)
//
// 参数：
//   radius   —— 模糊半径，决定"多粗的细节算细节"。太小只能锐化噪点，
//               太大会在边缘产生明显的白边/黑边（光晕）。
//   amount   —— 强度，1.0 为原强度。
//   threshold—— 阈值。差异小于它的地方不锐化。这是**抑制噪点什么的关键**：
//               平坦区域的微小差异（噪点）不该被放大，只有真正的边缘
//               （差异大）才该锐化。
QImage unsharpMask(const QImage &src, qreal radius,
                   qreal amount = 1.0, int threshold = 0);

// ---------------------------------------------------------------------------
//  其它
// ---------------------------------------------------------------------------

// 像素化（马赛克）
QImage pixelate(const QImage &src, int blockSize);

// 添加噪点（用于制造颗粒感）
QImage addNoise(const QImage &src, qreal amount, quint32 seed = 0);

} // namespace filters
} // namespace zl
