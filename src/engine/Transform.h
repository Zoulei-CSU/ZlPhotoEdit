#pragma once

// ============================================================================
//  Transform.h —— 图层级几何变换
// ----------------------------------------------------------------------------
//  与 Geometry.h 的分工：
//    Geometry.h —— 图像级操作。图像大小、画布大小、图像旋转、裁剪。
//                  这些操作会**改变画布尺寸**，需要同步所有图层与选区。
//    Transform.h —— 图层级操作。移动、缩放、旋转、翻转单个图层的内容。
//                  画布尺寸不变，只改变图层内部的像素分布。
//
//  这个区分很重要，因为两者的实现与撤销策略完全不同：
//    · 图像级 —— 影响所有图层，必须整层快照 + 压缩，代价高
//    · 图层级 —— 只影响一个图层，但内容会移动，也建议整层快照
//
//  注意：目前"翻转"在两层都有实现（图像级翻转会同步所有图层），
//  这是有意的 —— 用户在菜单里看到的"水平翻转"作用于整张图，
//  而图层面板里的翻转只作用于当前图层。
// ============================================================================

#include "core/ImageTypes.h"
#include "engine/Geometry.h"

#include <QImage>
#include <QRect>
#include <QTransform>

namespace zl {
namespace transform {

// ---------------------------------------------------------------------------
//  移动
// ---------------------------------------------------------------------------

// 把图像内容在画布内平移指定偏移量。
//
// 与画布大小调整的区别：这里画布尺寸不变，超出边界的部分直接丢弃
// （不会自动扩画布）。移动工具用的就是它。
//
// 若需要"移动到边界外时自动扩画布"，那是 Document 层的决策，
// 不应由这个纯函数负责。
QImage translate(const QImage &src, const QPoint &delta);

// ---------------------------------------------------------------------------
//  缩放（图层内容缩放，画布尺寸不变）
// ---------------------------------------------------------------------------

// 围绕指定锚点缩放图层内容。缩放后的内容仍放在原尺寸画布中，
// 超出部分裁掉，不足部分保持透明。
//
// anchor 用归一化坐标表示（0,0 = 左上，0.5,0.5 = 中心，1,1 = 右下），
// 这样调用方无需知道画布尺寸就能表达"围绕中心缩放"。
QImage scaleAbout(const QImage &src, qreal factor,
                  const QPointF &anchor = QPointF(0.5, 0.5),
                  ResampleMethod method = ResampleMethod::Bicubic);

// 非等比缩放版本
QImage scaleAbout(const QImage &src, qreal factorX, qreal factorY,
                  const QPointF &anchor = QPointF(0.5, 0.5),
                  ResampleMethod method = ResampleMethod::Bicubic);

// ---------------------------------------------------------------------------
//  旋转（图层内容旋转，画布尺寸不变）
// ---------------------------------------------------------------------------

// 围绕图像中心旋转图层内容。
//
// 注意：旋转后的四个角会超出原画布而被裁掉。如果用户想要"不裁切"，
// 应该用图像级的图像旋转（Geometry.h 的 rotateImage）。
QImage rotateAboutCenter(const QImage &src, qreal angleDeg,
                         ResampleMethod method = ResampleMethod::Bicubic);

// 围绕任意锚点旋转
QImage rotateAbout(const QImage &src, qreal angleDeg, const QPointF &anchor,
                   ResampleMethod method = ResampleMethod::Bicubic);

// ---------------------------------------------------------------------------
//  翻转
// ---------------------------------------------------------------------------

QImage flip(const QImage &src, FlipDirection dir);

// ---------------------------------------------------------------------------
//  任意仿射变换
// ---------------------------------------------------------------------------

// 对图像应用任意仿射变换（结果画布尺寸不变）。
//
// 参数：
//   src    —— 源图像
//   m      —— 变换矩阵，作用于**源图像坐标**
//   method —— 插值方式
//
// 用于将来的自由变换（Ctrl+T）功能。当前 Phase 1 尚未用到，
// 但接口先留好，避免将来改动现有函数的签名。
QImage applyTransform(const QImage &src, const QTransform &m, ResampleMethod method);

// ---------------------------------------------------------------------------
//  内容包围盒
// ---------------------------------------------------------------------------

// 计算图像中"非透明像素"的包围盒。
//
//  用途：
//    · 画布缩小时的智能适配（只关心有内容的部分）
//    · 裁剪工具的初始建议框
//    · "裁切到内容"功能
//
//  ★ 性能提醒 ★
//    朴素实现要遍历全部像素。4000×3000 = 1200 万像素，每次调用约 2~3ms。
//    这在单个操作里没问题，但如果每次重绘都调用就会成为瓶颈。
//    因此 Document 层必须**缓存**这个结果，只在像素变化时失效重算。
//    不要在 paintEvent 里直接调用本函数。
//
//  实现优化：逐行扫描，先快速判断整行是否全透明（用 memchr 类似的思路），
//  可以跳过大量空行 —— 实际使用中大部分行都是全透明的。
QRect contentBounds(const QImage &src);

// 裁切到内容包围盒。
// 可选留出 padding 像素的边距（透明），避免内容紧贴边缘。
QImage trimToContent(const QImage &src, int padding = 0);

} // namespace transform
} // namespace zl
