#pragma once

// ============================================================================
//  Geometry.h —— 几何变换的公共基础设施
// ----------------------------------------------------------------------------
//  本文件处理"三个概念容易被混为一谈"的问题。这是本工程里最容易设计混乱
//  的一块，所以先把概念钉清楚：
//
//  ┌─────────────────────────────────────────────────────────────────┐
//  │ 概念 A：图像大小（Image Size）                                    │
//  │   · 像素被缩放：内容跟着变大变小                                   │
//  │   · 需要重采样，图像会变模糊或变锐                                  │
//  │   · 例：2000×1500 缩到 1000×750                                  │
//  │ 概念 B：画布大小（Canvas Size）                                   │
//  │   · 像素不缩放：只改变"容器"的边界                                 │
//  │   · 不重采样，图像质量完全无损                                     │
//  │   · 缩小时裁掉超出部分，放大时补上底色                              │
//  │   · 例：2000×1500 的图，画布改成 3000×3000，内容位置不动，四周补白   │
//  │ 概念 C：裁剪（Crop）                                             │
//  │   · 本质就是"按指定的新边界缩小画布"，是 B 的一个特例                 │
//  │   · 因此实现上复用 B 的代码路径，不必单独做一套                      │
//  └─────────────────────────────────────────────────────────────────┘
//
//  统一入口是 applyGeometryChange()：所有几何操作（缩放、画布调整、旋转、
//  翻转、裁剪）最终都归结为"一个 QTransform + 一个新尺寸"。把边界情况
//  （负偏移、内容超出、选区同步）只写一遍，避免每个对话框各写一套逻辑。
// ============================================================================

#include "core/ImageTypes.h"

#include <QImage>
#include <QTransform>
#include <QRect>
#include <QSize>
#include <QPoint>
#include <QColor>

namespace zl {

// ---------------------------------------------------------------------------
//  九宫格锚点
// ---------------------------------------------------------------------------
//  画布大小调整时用来决定"原有内容放在新画布的哪个位置"。
//  对应对话框里的 3×3 网格按钮。
enum class Anchor {
    TopLeft = 0,      TopCenter,      TopRight,
    MiddleLeft,       Center,         MiddleRight,
    BottomLeft,       BottomCenter,   BottomRight
};

// 根据锚点计算"内容相对新画布的偏移量"。
//
// 参数 newSize 是新画布尺寸，oldSize 是原画布尺寸，返回值为内容左上角在
// 新画布中的坐标。
//
// 这个函数是画布大小调整的核心 —— 九宫格的九个行为全部由它统一表达，
// 不必写九个 switch 分支。
QPoint anchorOffset(Anchor anchor, const QSize &oldSize, const QSize &newSize);

// 智能适配偏移。
//
//  这是"画布缩小时"的默认行为：普通锚点会让超出画布的内容被裁掉，
//  而智能适配会在"内容完整可见"的前提下，求出最接近用户所选锚点意图的
//  偏移量，从而避免无声地丢掉画面内容。
//
//  算法：
//    1. 先按锚点算出基础偏移 baseOffset
//    2. 若内容在新画布内完整可见 → 直接返回 baseOffset
//    3. 否则在"能装下内容"的合法偏移范围内，取最接近 baseOffset 的值
//    4. 若内容比新画布还大（装不下）→ 退化为按锚点裁切，返回 baseOffset
//
//  参数 contentRect 是当前内容的实际包围盒（由 Document::contentBounds()
//  得到），而非整个旧画布 —— 用户关心的是"我画的东西别丢"，
//  透明边缘丢了无所谓。
QPoint computeSmartOffset(const QRect &contentRect,
                          const QSize &oldSize,
                          const QSize &newSize,
                          Anchor anchor);

// 画布尺寸变化的**实际**偏移（已包含"要不要走智能适配"的策略判断）。
//
//  ★ 这是 Document 与对话框预览的唯一共同来源 ★
//
//    "智能适配"的启用条件不是简单的 `smart == true`：它只在**缩小时**
//    才有意义（放大时按锚点放置本来就完整可见）。这段策略如果被复制成
//    两份 —— 一份在 Document::resizeCanvas 里执行、一份在对话框的预览
//    示意图里绘制 —— 那么两边迟早会分叉，表现为"预览说不会裁切，
//    确定后却发现被裁掉了"。宁可多一个函数，也不要两份策略。
//
//  参数 contentRect 传 QRect() 表示"内容包围盒未知/为空"，
//  此时智能适配退化为纯锚点行为（与 computeSmartOffset 的约定一致）。
QPoint canvasResizeOffset(const QRect &contentRect,
                          const QSize &oldSize,
                          const QSize &newSize,
                          Anchor anchor,
                          bool smart);

// ---------------------------------------------------------------------------
//  「打开为图层」的尺寸适配
// ---------------------------------------------------------------------------
//  把一张外来图片放进当前画布时，只有两个决策：
//    ① 画布要不要变大？变到多大？
//    ② 图片放在画布的哪个位置？
//
//  ★ 为什么这两条要放在 engine 层而不是写在 MainWindow 里 ★
//    它们都是**纯几何**（与 QtWidgets 无关），而且是最容易"看着对、
//    实际错一位"的地方 —— 写死在 MainWindow::openAsLayer() 里就只能靠
//    人眼看结果，抽出来才能被 geometry_test 直接断言。
//    与 anchorOffset / canvasResizeOffset 被抽出来的理由完全一样。
//
//  ★ 为什么"扩大"取逐维最大值（并集），而不是等比缩放或取较大的一边 ★
//    并集是**唯一不丢内容**的选择：画布扩到刚好装下两者，超出的部分
//    不存在，所以不需要任何"缩放/裁剪"决策，也不需要重采样。
//    画面质量与"这个功能只做加法"的直觉都对得上。

// 能同时容纳 a 与 b 的最小尺寸（逐维取大）。
//
//  ★ 刻意不做"空尺寸"的特判 ★
//    推演过：任何输入下它都与逐维取大等价，加特判只会写出死代码
//    （见 .cpp 里的说明）。调用方保证尺寸有效 —— 画布 ≥ 1×1，
//    图片来自已成功解码的 QImage。
QSize unionSize(const QSize &a, const QSize &b);

// 把 itemSize 居中放进 canvasSize 的左上角坐标。
//
//  ★ 不钳到非负 ★
//    itemSize 比 canvasSize 大时这里会返回负数 —— 这是**故意**的。
//    本项目所有放置都发生在"已经算过并集的画布"上（见 unionSize），
//    此时差值必然非负；而万一有人传了更小的画布，负数会让内容居中溢出，
//    比"钳到 0、悄悄把内容挪到左上角"更接近调用者的真实意图，
//    也更容易在自检里被发现。
QPoint centeredOffset(const QSize &canvasSize, const QSize &itemSize);

// ---------------------------------------------------------------------------
//  旋转
// ---------------------------------------------------------------------------

// 90° 倍数旋转时，判断给定的角度是否真的接近 90/180/270。
//
//  为什么需要容差：角度经过多次浮点运算后，90 度可能变成 89.999999999。
//  如果用 `angle == 90.0` 判断就会走错分支，导致本来应该无损的 90° 旋转
//  走了插值路径，图像被无谓地模糊一次。
//
//  容差取 0.01 度 —— 远小于用户能感知的角度差异，又远大于浮点误差量级。
bool isRightAngle(qreal angleDeg, int *quarterTurnsOut = nullptr);

// 归一化角度到 [0, 360) 区间。
qreal normalizeAngle(qreal angleDeg);

// ---------------------------------------------------------------------------
//  翻转
// ---------------------------------------------------------------------------
enum class FlipDirection {
    Horizontal,   // 左右翻转（水平镜像）
    Vertical      // 上下翻转（垂直镜像）
};

// ---------------------------------------------------------------------------
//  统一几何变换
// ---------------------------------------------------------------------------

// 几何变换的参数包。
// 把参数集中成一个结构体而不是一长串函数参数，理由是几何变换的可选项
// 会持续增加（将来可能加透视变形），用结构体能避免每加一项就改所有调用点。
struct GeometryParams
{
    QTransform transform;                          // 作用于内容坐标的变换
    QSize      newCanvasSize;                      // 变换后的画布尺寸
    ResampleMethod interpolation = ResampleMethod::Bicubic;
    QColor     fillColor = Qt::transparent;        // 画布扩大部分的填充色

    // 变换后内容在新画布中的偏移（通常用于把旋转后的内容居中）
    QPoint     contentOffset;
};

// 对单张图层位图应用几何变换。
//
// 步骤：
//   1. 用 QTransform 把图像变换到临时画布上（尺寸为变换后的内容包围盒）
//   2. 再把临时结果按 contentOffset 贴到 newCanvasSize 的画布上，空白处填 fillColor
//
// 说明为什么不用 QImage::transformed()：它返回的是变换后的紧凑包围盒，
// 而这个包围盒的尺寸/原点与我们需要的目标画布尺寸通常不一致。
// 分两步走逻辑更清晰，也便于处理"画布比内容大"的情况。
QImage applyGeometry(const QImage &src, const GeometryParams &params);

// 便捷版本：旋转任意角度。
// 返回旋转后的图像，画布会自动扩大到刚好容纳旋转后的内容（不裁切）。
//
// fillColor 是**画布扩大部分**的填充色（旋转后四角必然空出来一块）。
// 默认透明；对话框里可选透明 / 背景色 / 白 / 黑。
//
// ★ 90° 倍数角度下 fillColor 被忽略 ★
//   那时走 rotateQuarterTurns() 的无损路径，画布正好容纳、一个空像素都没有，
//   填充色无从体现。所以"输入 90° 却选了黑色却没变黑"不是 bug。
QImage rotateImage(const QImage &src, qreal angleDeg, ResampleMethod method,
                   const QColor &fillColor = Qt::transparent);

// 便捷版本：90° 倍数旋转。走无损路径（不插值）。
// quarterTurns 为 1/2/3 分别表示顺时针 90°/180°/270°。
QImage rotateQuarterTurns(const QImage &src, int quarterTurns);

// 便捷版本：翻转。走无损路径。
QImage flipImage(const QImage &src, FlipDirection dir);

// 便捷版本：裁剪（从图像中取出指定矩形）
QImage cropImage(const QImage &src, const QRect &rect);

// ---------------------------------------------------------------------------
//  计算辅助
// ---------------------------------------------------------------------------

// 计算画布尺寸从 oldSize 变为 newSize 时，锚点对应的偏移。
// 这是 anchorOffset 的重载版本，直接返回 QPoint 形式的偏移（新坐标 - 旧坐标）。
QPoint canvasResizeDelta(const QSize &oldSize, const QSize &newSize, Anchor anchor);

// 已知图像尺寸与旋转角度，计算旋转后"刚好容纳"的包围盒尺寸。
// 用于任意角度旋转时确定新画布尺寸。
QSize rotatedBoundsSize(const QSize &size, qreal angleDeg);

// ---------------------------------------------------------------------------
//  百分比 ↔ 像素（尺寸类对话框的"单位"换算）
// ---------------------------------------------------------------------------
//
//  ★ 这两个函数是百分比换算的**唯一**来源 ★
//
//    与 canvasResizeOffset() 同样的道理：换算里有两处极易分叉的细节 ——
//    取整方式、以及退化输入（原尺寸 ≤ 0）的处理。一旦在对话框里另写一遍
//    `qRound(original * p / 100.0)`，就迟早出现"输入 33%，显示的却是 34%"
//    这类只在某些尺寸下才复现的怪现象。宁可多两个函数，也不要两份算法。
//
//  ★ 为什么用整数而不是浮点 ★
//    percent 与 original 都是整数，乘积最大 2e6 × 2e4 = 4e10，用 qint64
//    承载后再做整数四舍五入，结果在任何输入下都是确定的。走 double 虽然
//    也够精确，但"先乘后除"与"先除后乘"在 .5 边界上的取舍就成了实现细节，
//    而这里的取整规则是要被写进文档、被测试断言的契约。
//
//  取整一律**四舍五入、.5 远离零**。截断会让"缩到 50% 再放回 100%"这种
//  往返操作产生单向漂移（每次都少一像素），缩放两次就看得出来变小了。
//
//  退化输入：original ≤ 0 时返回 0（不产生除零，也不假装有一个尺寸）。
//  调用方负责把结果钳到合法范围（对话框那边用 qBound(1, …, max)）。

// 百分比 → 像素。percent 是"占原尺寸的百分之几"（100 表示不变）。
int percentToPixels(int percent, int original);

// 像素 → 百分比。是 percentToPixels 的反解（四舍五入），用于把目标尺寸
// 显示成百分比。整数百分比是表达力有限的一把尺子：原尺寸很小时（例如
// 7 像素宽），相邻两个百分比对应的可能是同一个像素数 —— 此时反解出来
// 的数字会与用户的输入略有出入，但**目标尺寸（真值）不受影响**，
// 信息面板里写的始终是真实生效的像素数。
int pixelsToPercent(int pixels, int original);

} // namespace zl
