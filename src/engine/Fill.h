#pragma once

// ============================================================================
//  Fill.h —— 油漆桶的填充引擎
// ----------------------------------------------------------------------------
//  架构规划 3.6 节把"容差算法"定清楚了，本文件是它的实现。四件事：
//
//    ① colorDistance  —— 三通道欧氏色差（0-255），容差滑块的度量
//    ② fillDistance   —— 填充判据用的综合色差（再带上 alpha，见下）
//    ③ floodFill      —— 扫描线种子填充（不递归，不爆栈）
//    ④ composeFill    —— 把覆盖度蒙版合成到图层（复用画笔那条合成路径）
//
//  ★★ 为什么不返回"填好的图像"，而返回一张覆盖度蒙版 ★★
//
//  这是本文件最重要的一个设计决定。若 floodFill 直接产出结果图像，
//  那么"与选区求交""按不透明度混合""撤销快照取哪一块"这三件事就都要
//  在填充算法内部实现一遍，而它们与画笔完全同构。
//
//  返回蒙版之后，填充的收尾直接复用 composeStroke()（见 Brush.h）：
//
//      composeStroke(填充前的图层, 覆盖度蒙版, 填充色, false, 选区蒙版)
//
//  于是"选区边缘不泄漏""预乘空间合成""不透明度语义"三条规则
//  在整个工程里**只有一份实现**，画笔与油漆桶不可能出现行为分叉。
//
//  ★★ 为什么不能直接用 colorDistance 做判据 ★★
//
//  它是**三通道**的。而图层位图是 ARGB32_Premultiplied，于是：
//
//      不透明的黑  (0, 0, 0, 255)  → 预乘后 (0, 0, 0, 255)
//      全透明      (0, 0, 0,   0)  → 预乘后 (0, 0, 0,   0)
//
//  两者的 RGB 分量完全相同，三通道色差为 **0**。用户在一张实心黑图上点
//  油漆桶，填充会**溢进整张透明画布**（如果画布比图大），或者在"黑图形
//  与透明背景"之间乱串 —— 而且不报错，只是"填得比想象的多"。
//
//  所以填充判据用 fillDistance()：在三通道色差之外取 alpha 差的最大值。
//  对绝大多数照片（alpha 全是 255）它与 colorDistance 完全等价，
//  一分钱都不多花；只有在真的有透明区域时才起作用。
//
//  ★ 本文件属于 engine 层 ★
//    只依赖 QtGui，绝不 include 任何 QtWidgets 头文件。
// ============================================================================

#include <QImage>
#include <QRect>
#include <QPoint>

namespace zl {

// ---------------------------------------------------------------------------
//  容差：色差度量
// ---------------------------------------------------------------------------

// 三通道欧氏色差，归一化到 0-255。三通道等权重。
//
// ★ 用欧氏距离而不是"逐通道差值取最大" ★
//
//   先纠正一个容易说反的地方：**逐通道判据其实比欧氏距离更严格**。
//   逐通道是"每个通道的差都 ≤ 容差"，而欧氏是"均方根 ≤ 容差"；
//   均方根永远 ≤ 最大分量，所以逐通道接受的一定被欧氏接受，反之不然。
//   举例（容差 40）：
//     纯红 (255,0,0) 与 (195,0,0)：逐通道差 60 → 拒绝；欧氏 34.6 → 接受
//   原因是单通道的大偏移会被另外两个通道的 0 偏移"摊薄"。
//
//   选欧氏的真正理由不是"谁更准"，而是**尺度统一、手感线性**：
//   结果归一化到 0-255 之后，"容差 32" 就是一个可解释的刻度，
//   用户拖滑块时容差与填充面积的关系是平滑单调的，不会有台阶。
//   这也是架构规划 3.6 节定下的口径。
//
// ★ 除以 3 再开方的意义 ★
//   见上：把结果归一化到 0-255。注意这带来一个副作用 ——
//   单通道差 d 对应的色差是 d/√3 ≈ 0.577d，所以"容差 32"
//   约等于"每通道 55"。灰阶上色差与灰阶差是 1:1，这是最好用的直觉。
int colorDistance(QRgb a, QRgb b);

// 填充判据用的综合色差 = max(三通道色差, alpha 差)。
// 理由见文件头「为什么不能直接用 colorDistance」。
int fillDistance(QRgb a, QRgb b);

// ---------------------------------------------------------------------------
//  填充参数与结果
// ---------------------------------------------------------------------------

struct FloodFillParams
{
    // 起点（图像坐标）。越界时结果为空。
    QPoint seed;

    // 容差 0-255。0 表示"只填与起点完全同色的像素"。
    int tolerance = 32;

    // true  —— 只填与起点**连通**的区域（扫描线算法）
    // false —— 填全图所有色差在容差内的像素，不管连通性
    bool contiguous = true;

    // 是否生成边缘过渡带（抗锯齿）。
    // 关掉的话边缘是硬台阶，放大后锯齿明显。
    bool antialias = true;

    // 过渡带宽度（色差单位）。只有 antialias 为 true 时有意义。
    //
    // 取值 32 的理由：容差本身是 0-255 的色差刻度，32 约等于
    // "一个台阶"（相当于每通道 18 的差异）。再宽会让边界糊成一片，
    // 再窄则起不到抗锯齿的作用。
    int softBand = 32;
};

struct FillResult
{
    // 覆盖度蒙版：Grayscale8，与原图同尺寸。
    //   0   = 完全没填到
    //   255 = 完全填充
    //   1~254 = 过渡带（按距离线性衰减）
    QImage mask;

    // 蒙版中非零覆盖的包围盒（图像坐标）。
    // ★ 调用方靠它把"合成 + 撤销快照"限制在这一块里 ★
    //   不然一张 4000×3000 的图点一下油漆桶，就要拷两份整层快照
    //   （48MB × 2）去压撤销栈。
    // 空矩形表示一个像素都没填到（调用方应当连命令都不压）。
    QRect bounds;

    bool isEmpty() const { return bounds.isEmpty(); }
};

// ---------------------------------------------------------------------------
//  扫描线种子填充
// ---------------------------------------------------------------------------
//  返回覆盖度蒙版，不做任何合成。合成交给 composeFill()。
//
//  ★★ 必须用"已填充标记"，不能靠"颜色是否已变成填充色"来判断 ★★
//
//  最朴素的写法是：把像素改成填充色，然后靠"这个像素颜色还是不是种子色"
//  来决定要不要处理。这在**单次填充**里凑合能用，但有一个致命前提 ——
//  填充色本身不能落在容差范围内。
//
//  用户完全可能用容差 255 或"把黑填成黑"，那时填充色与种子色距离为 0，
//  于是每个像素都会被反复判定为"未填充"，相邻线段互相压栈，
//  **栈无限增长直到内存耗尽**。这是扫描线填充最经典的 bug，
//  而且症状（卡死 / 内存爆掉）与"算法写错"看起来完全无关。
//
//  本实现用一个 QBitArray 记录"这个像素是否已经属于填充区域"，
//  与颜色彻底解耦。
//
//  ★ 扩展判据与覆盖度判据是**两个**阈值 ★
//    · 扩展（哪些像素属于区域）：d <= tolerance + softBand
//    · 覆盖度（每个像素填多满）：
//        d <= tolerance                → 255
//        d <= tolerance + softBand     → 按距离线性衰减到 0
//    两者都以**种子色**为参照，不是与邻居比较 —— 这样区域范围
//    与遍历顺序无关（"从哪边开始填"不影响结果），也不会沿着渐变
//    无限蔓延。
FillResult floodFill(const QImage &src, const FloodFillParams &params);

// ---------------------------------------------------------------------------
//  合成
// ---------------------------------------------------------------------------
//  把覆盖度蒙版按填充色合成到 base 上，返回**新的**位图（不改动入参）。
//
//  实现上直接转调 composeStroke()（engine/Brush.h），所以：
//    · 全程在预乘空间运算（合成类运算的正确做法，与 LUT 类相反）
//    · 选区蒙版在"颜色预乘之前"乘进覆盖度，选区外缘不会出现淡影
//    · fillColor 的 alpha 通道会与覆盖度相乘 → 这就是"填充不透明度"的语义
//
//  base          必须是 ARGB32_Premultiplied，且尺寸与 mask 相同
//  mask          覆盖度（Grayscale8，尺寸与 base 相同）
//  fillColor     填充色
//  selectionMask 选区蒙版（Grayscale8）。传空 QImage 表示"全选"。
QImage composeFill(const QImage &base, const QImage &mask,
                   const QColor &fillColor,
                   const QImage &selectionMask = QImage());

} // namespace zl
