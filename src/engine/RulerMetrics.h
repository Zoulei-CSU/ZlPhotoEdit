#pragma once

// ============================================================================
//  RulerMetrics.h —— 标尺的刻度与单位换算（纯函数）
// ----------------------------------------------------------------------------
//  一句话：给定"当前缩放 + 单位 + DPI"，算出**该画到哪几个刻度、数值怎么标**。
//  本文件不建控件、不碰 QPainter、不碰 Document —— 与 engine 其他文件同规矩：
//  只看输入出输出，**可以被离线自检直接断言**。
//
//  ★★ 为什么刻度选择必须是纯函数、不能写在 RulerWidget 里 ★★
//
//    刻度是"看起来很主观、其实可判定"的东西：放大到 800% 要显示到像素级、
//    缩到 10% 刻度要粗到几百图像像素一级，数值还不能挤成一片。写进 paintEvent 里
//    唯一的验收方式就是"看图"—— 而那正是我们不许出现的验收方式
//    （见 docs/实现铁律.md 第九章 / 三类静默失效之"自绘控件"）。
//
//    抽成纯函数之后，"缩放 0.1 → 主刻度 100 / 缩放 8 → 主刻度 1"
//    这类断言可以逐条写死，改坏立刻变红。
//
//  ★★ 为什么单位换算要带 DPI ★★
//
//    图像本身只有像素，没有物理尺寸 —— cm / mm / inch / pt 全都依赖 DPI
//    这个**元数据**（默认 96，见 docs/架构规划.md 3.10）。同一张 1000px 的图
//    在 72dpi 与 300dpi 下"看起来"分别是 13.9 英寸与 3.3 英寸，
//    标尺上的数字自然不同。DPI 由调用方传进来，本文件不猜。
// ============================================================================

#include <QtGlobal>
#include <QString>

namespace zl {
namespace rulermetrics {

// 标尺单位。顺序与"视图 → 标尺单位"菜单一致。
enum class Unit {
    Pixel,        // 像素（默认）
    Centimeter,   // 厘米
    Millimeter,   // 毫米
    Inch,         // 英寸
    Point,        // 点（1/72 英寸，排版用）
};

// 单位个数。
constexpr int kUnitCount = 5;

// 按下标取单位 / 单位反查下标。
//
//  ★ 为什么要有这两个函数，而不是直接用 static_cast ★
//    "菜单顺序 / QSettings 里存的下标 / 枚举值"三处必须一致。用 static_cast
//    就等于把"枚举的整数值"当成了公开协议 —— 以后有人在 Unit 中间插一个
//    新单位，菜单与存档会**静默错位**（存的是"1"，读出来变成"厘米"）。
//    改成一张显式的表之后，插新单位只会让表变一下，协议位置不变。
Unit unitAt(int index);      // 越界返回 Unit::Pixel
int  unitIndex(Unit unit);   // 未知返回 0

// 1 个"单位"对应多少**图像像素**。
//   Pixel → 1（恒定，与 DPI 无关）
//   Inch  → dpi
//   cm/mm/pt → 由 dpi 派生（2.54 / 25.4 / 72）
// dpi <= 0 时按 96 处理（防"元数据缺失 → 全线算成 0"）。
qreal pixelsPerUnit(Unit unit, int dpi);

// 取"好看的"步长：返回 >= minStep 的最小 1 / 2 / 5 × 10^n。
//
//   ★ 为什么不是"直接乘 2" ★
//     倍率法（1,2,4,8…）会画出 1000 / 2000 / 4000 这种刻度，
//     用户读数字要数位；1/2/5 是人类读数的习惯刻度（同"分度值"惯例）。
//
//   minStep <= 0（或 NaN）→ 返回 1.0（调用方不该走到这里，但静默返回 0
//   会让刻度变成"画不出任何线"，比一个兜底常数更难查）。
qreal niceStep(qreal minStep);

// 一组主/次刻度间距。**单位是"单位数"**，不是像素 ——
// 乘以 pixelsPerUnit() 才是图像像素。
struct Ticks {
    qreal major = 1.0;    // 带数字的主刻度
    qreal minor = 0.2;    // 不带数字的次刻度（主刻度的 1/5）
};

// 依据当前缩放挑一组刻度间距。
//   zoom              —— 画布当前的"图像像素 → 屏幕像素"倍率
//   unit / dpi        —— 单位制与 DPI
//   minLabelSpacingPx —— 两**个带数字的主刻度**之间，屏幕上至少留多少像素
//                        （太小则数字叠字；RulerWidget 传的是"标签宽度 + 间距"）
//
//   ★ 判据在"屏幕像素"上，不在图像像素上 ★
//     刻度密不密只跟屏幕上看起来怎么样有关。若按图像像素判，
//     缩到 5% 时主刻度还是 100 图像像素 = 屏幕上 5 像素 → 数字全叠在一起。
Ticks chooseTicks(qreal zoom, Unit unit, int dpi, qreal minLabelSpacingPx);

// 把"以单位计的数值"格式化成刻度标签。
//   valueInUnits —— 已经除以 pixelsPerUnit 之后的值
//   major        —— 当前主刻度间距（用来决定保留几位小数）
//
//   像素单位一律整数；物理单位在小刻度时才带小数（inch 常有 0.5 / 0.25）。
//   "-0" 要显示成 "0"（否则 0 刻度附近会出现 "-0" 这种看着像 bug 的标签）。
QString formatLabel(qreal valueInUnits, Unit unit, qreal major);

} // namespace rulermetrics
} // namespace zl
