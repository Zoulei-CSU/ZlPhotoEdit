#pragma once

// ============================================================================
//  Resample.h —— 高质量重采样
// ----------------------------------------------------------------------------
//  Qt 只提供两种插值：
//    · Qt::FastTransformation  —— 邻近取样（最近邻）
//    · Qt::SmoothTransformation —— 双线性
//  两者都不够：缩放照片时双线性会产生明显的锯齿和模糊，专业编辑器都用
//  双三次（bicubic）。因此本工程自行实现。
//
//  ★ 两个经典错误（这是本文件存在的核心价值）★
//
//  错误一：直接做二维 4×4 卷积
//    双三次需要 4×4 邻域。如果对每个输出像素都遍历 16 个源像素，
//    复杂度是 O(W1·H1·16)。而双三次核是**可分离**的 —— 可以先在水平
//    方向做一次一维卷积，再在垂直方向做一次。这样复杂度降到
//    O(W0·H1·4 + W1·H1·4)，对于常见的等比缩放约快 4 倍。
//    几何级数的差距，缩放大图时是"能用"和"转圈等"的区别。
//
//  错误二：忘记归一化权重
//    当输出像素映射到源图的边界附近时，4 个采样点中会有部分落在图像外。
//    常见做法是 clamp（把越界的坐标夹到边缘像素），此时取样点会重复，
//    于是 4 个权重之和不再是 1，而是略大或略小。
//    后果：整张图整体变亮或变暗，且**偏差量随缩放比例变化** ——
//    缩小 50% 和缩小 73% 的亮度偏移不一样，用户完全无法理解为什么
//    "只是改了个尺寸，图怎么就变灰了"。
//    正确做法：每次取完 4 个权重后，除以它们的和，强制归一。
//
//  ★ 边界处理 ★
//    越界坐标用 clamp（重复边缘像素），而不是视为透明。
//    视为透明会在图像四周产生一圈暗边（因为边缘与"透明黑"做了插值）。
//
//  ★ 在预乘 alpha 空间运算 ★
//    与 LUT 查表不同，重采样的加权求和**应该**在预乘空间做 ——
//    数学上这等价于按 alpha 加权平均颜色，是正确的结果。
//    如果在非预乘空间做，透明区域的 RGB 值会参与插值，产生彩边。
// ============================================================================

#include "core/ImageTypes.h"

#include <QImage>
#include <QVector>
#include <QtMath>   // qSin / qAbs / qFloor …
#include <QtGlobal>

namespace zl {
namespace resample {

// ---------------------------------------------------------------------------
//  核函数
// ---------------------------------------------------------------------------

// Keys 三次卷积核（也叫 Mitchell-Netravali 家族的 B=0, C=0.5）：
//
//              | 1.5|x|³ - 2.5|x|² + 1         , |x| <= 1
//   W(x) =    | -0.5|x|³ + 2.5|x|² - 4|x| + 2  , 1 < |x| < 2
//              | 0                              , |x| >= 2
//
//  a 参数控制锐度：
//    a = -0.5  —— 标准值，质量与锐度的平衡点（默认）
//    a = -0.75 —— 更锐，但可能出现轻微振铃
//    a = -1.0  —— 最锐，振铃明显
inline qreal cubicKernel(qreal x, qreal a = -0.5)
{
    x = qAbs(x);

    if (x <= 1.0) {
        return ((a + 2.0) * x - (a + 3.0)) * x * x + 1.0;
    }
    if (x < 2.0) {
        return (((x - 5.0) * x + 8.0) * x - 4.0) * a * x;
    }
    return 0.0;
}

// Lanczos 核：sinc(x) * sinc(x/a)，a 通常取 3。
// 比双三次更锐利，但会引入轻微振铃（高对比边缘附近出现波纹）。
inline qreal lanczosKernel(qreal x, qreal a = 3.0)
{
    x = qAbs(x);
    if (x < 1e-8)
        return 1.0;
    if (x >= a)
        return 0.0;

    // ★ 不用 M_PI ★
    //   M_PI 不是 C++ 标准，而是 POSIX 扩展。MSVC 只在 <math.h> 里且
    //   _USE_MATH_DEFINES 被定义时才提供它，而 Qt 的 qmath.h 不保证
    //   把它引进来 —— 直接使用会报 "未声明的标识符 M_PI"。
    //   用字面常量则完全不依赖任何头文件的宏定义行为。
    constexpr qreal kPi = 3.14159265358979323846;

    const qreal pix = kPi * x;
    return (a * qSin(pix) * qSin(pix / a)) / (pix * pix);
}

// ---------------------------------------------------------------------------
//  预计算的重采样表
// ---------------------------------------------------------------------------
//  这是性能的关键：输入坐标到输出坐标的映射关系（以及对应的权重）在整个
// 缩放过程中是**固定不变**的。如果对每个像素都重新算一遍权重，浮点三角函数
// 的开销会占掉大半时间。
//
//  预计算一次，后续每个像素只做"查表 + 乘加"，速度快得多。
// ---------------------------------------------------------------------------
struct ResampleTable
{
    int   srcSize = 0;      // 源尺寸（宽或高）
    int   dstSize = 0;      // 目标尺寸
    int   support = 4;      // 每个输出像素参与运算的源像素个数（双三次为 4）

    // ★ 用 QVector 而不是 QList ★
    //   这两个数组需要"预先 resize 到固定长度"再逐项赋值，
    //   而 Qt5 的 QList 没有 resize()，也没有连续内存保证。
    //   用 QVector：Qt5 下是真正连续的数组，Qt6 下是 QList 的别名，
    //   两种情况下 at()/下标访问都可用，代码无需分支。
    QVector<int>   start;     // 每个输出位置的源起始索引，长度 dstSize
    QVector<qreal> weights;   // 扁平存储的权重，长度 dstSize * support

    // 取第 dstIndex 个输出位置的第 k 个权重
    qreal weight(int dstIndex, int k) const
    {
        return weights.at(dstIndex * support + k);
    }
};

// 构建重采样表。kernel 为核函数，support 为半径（双三次为 2，Lanczos 为 3）。
ResampleTable buildTable(int srcSize, int dstSize, ResampleMethod method);

// ---------------------------------------------------------------------------
//  主入口
// ---------------------------------------------------------------------------

// 按指定算法缩放图像。
//
// 内部流程：
//   1. 构建水平与垂直两张重采样表
//   2. 预乘 alpha 转换（若输入不是预乘格式）
//   3. 水平方向一遍一维卷积 → 中间缓冲（32 位浮点，避免中间精度损失）
//   4. 垂直方向一遍一维卷积 → 输出图像
//   5. 转回原格式
//
// 注意中间缓冲用 32 位浮点而不是 8 位整数：两次卷积的舍入误差会累积，
// 大比例缩小（例如 8 倍）时在 8 位缓冲上能看出可见的色阶断层。
QImage scale(const QImage &src, const QSize &targetSize, ResampleMethod method);

// 便捷版本：按倍率缩放
QImage scale(const QImage &src, qreal factor, ResampleMethod method);

// ---------------------------------------------------------------------------
//  内部细节查询（供测试与调试使用）
// ---------------------------------------------------------------------------

// 返回指定算法需要的采样半径（双三次 2，Lanczos 3，双线性 1，邻近 0）
int kernelRadius(ResampleMethod method);

} // namespace resample
} // namespace zl
