#pragma once

// ============================================================================
//  Histogram.h —— 直方图统计（纯函数）
// ----------------------------------------------------------------------------
//  用途：曲线对话框的背景直方图、色阶对话框的输入分布、将来的"直方图面板"。
//
//  ★ 为什么必须转非预乘再统计 ★
//
//    图层位图是 Format_ARGB32_Premultiplied，RGB 分量**已经乘过 alpha**。
//    一个 50% 透明的纯白像素在预乘空间是 (128,128,128) ——
//    直接统计会让它落进亮度 128 的桶里，直方图整体向暗部偏移。
//    而用户看到的画面里，那个像素的确是亮的（它半透明地叠在棋盘格上）。
//    所以统计前必须先转成 Format_ARGB32。
//    （与 Lut.cpp 的预乘陷阱同源，只是这里错的不是颜色而是分布）
//
//  ★ 为什么跳过全透明像素 ★
//
//    alpha == 0 的像素，其 RGB 在预乘空间必然被归零（乘了 0），
//    在非预乘空间则是"未定义"（0/0）。把它们计入会在 0 处堆起一根
//    跟内容毫无关系的假尖峰 —— 空图层的直方图会看起来"全黑"。
//    默认跳过；需要看"整张画布"的分布时可以传 false。
// ============================================================================

#include <QImage>
#include <QVector>

namespace zl {
namespace histogram {

// 亮度直方图，256 个桶。
//
// 亮度公式与"去色"保持一致（0.299R + 0.587G + 0.114B）——
// 若两边不一致，用户在曲线里看到的直方图峰值位置会和去色后的灰度对不上。
QVector<int> luminance(const QImage &image, bool skipTransparent = true);

// 单通道直方图。channel：0=R、1=G、2=B，越界按 0 处理。
// 曲线对话框切到红/绿/蓝通道时，背景直方图也应该跟着换，
// 否则用户会在红色通道的曲线上看着亮度分布调，属于误导。
QVector<int> singleChannel(const QImage &image, int channel, bool skipTransparent = true);

// 归一化到 [0,1]，便于按比例绘制。
//
// logScale 为 true 时用 log(1+n)/log(1+max) 缩放。
// ★ 对数缩放不是可选的美化，而是必要的 ★
//   照片的直方图常在个别亮度值上极度集中（大片天空、大面积白背景），
//   线性缩放会让其余 99% 的柱子全被压成一条平线，看不出任何信息。
QVector<qreal> normalized(const QVector<int> &hist, bool logScale = true);

} // namespace histogram
} // namespace zl
