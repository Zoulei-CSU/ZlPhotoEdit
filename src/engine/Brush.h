#pragma once

// ============================================================================
//  Brush.h —— 笔刷引擎
// ----------------------------------------------------------------------------
//  本文件是整个"画笔"功能的算法核心。它只做四件事：
//
//    ① makeBrushTip        —— 生成笔尖（一个带硬度衰减的灰度蒙版）
//    ② interpolateStamps   —— 把"上一帧到这一帧"的直线补成一串落笔点
//    ③ stampTipInPlace     —— 把一个落笔点压进"整笔覆盖度蒙版"
//    ④ composeStroke       —— 把整笔覆盖度蒙版与颜色合成到图层上
//
//  ★ 为什么画笔不直接把颜色画到图层上，而要绕一层"累积蒙版" ★
//
//    这是画笔实现里最关键的一个设计决定。朴素做法是"每次移动就把
//    颜色刷到图层上"，但那会带来两个无法回避的问题：
//
//      ① 同一笔内部反复涂抹的区域会**越涂越深**。
//         画笔在画布上缓慢移动时，落笔点会大量重叠。如果每落一笔就
//         往图层上叠一次，重叠处的 alpha 会被反复累加，一条均匀的线
//         会变成"起手深、结束深、中间浅"的竹子状。
//
//      ② 橡皮无法撤销到"这一笔之前"。
//         橡皮是把像素的 alpha 乘以 (1 - 覆盖度)，这是**不可逆**运算
//         （乘 0 之后信息就没了）。如果边移动边擦，撤销时需要的是
//         "整笔开始前的图层"，而不是"上一帧的图层"。
//
//    引入一个与画布同尺寸的 Grayscale8 累积蒙版后，两个问题一起解决：
//      · 落笔用 **取最大** 而不是累加 → 同一笔内重叠不会变深
//      · 每次重绘都从"整笔开始前的图层"重算 → 完全幂等，无累积误差
//      · 整笔只产生一条撤销命令 → 按一次 Ctrl+Z 退回一笔，符合直觉
//
//    代价：每帧要重算整笔覆盖区域（而不是只算新增的那一小块）。
//    但重算范围被限制在笔画的包围盒内，而且只在预乘空间做一次
//    逐像素乘加，几百万像素约 1~3ms，拖动时完全够用。
//
//  ★ 本文件属于 engine 层 ★
//    只依赖 QtGui，绝不 include 任何 QtWidgets 头文件。
// ============================================================================

#include <QImage>
#include <QColor>
#include <QPointF>
#include <QRect>
#include <QVector>

namespace zl {

// ---------------------------------------------------------------------------
//  笔尖
// ---------------------------------------------------------------------------
//  一个直径 × 直径 的 Grayscale8 蒙版：中心 255，向外按硬度衰减到 0。
//
//  单独包一个结构体而不是只传 QImage，是为了把 diameter / radius 这两个
//  调用方几乎总要用到的量一起带上 —— 否则每个调用点都要自己算
//  （image.width() / 2 算起来一样，但"半径到底取整还是四舍五入"很容易
//   各处不一致，导致落笔点整体偏半个像素）。
// ---------------------------------------------------------------------------
struct BrushTip
{
    QImage mask;             // Grayscale8，diameter × diameter
    int    diameter = 0;
    int    radius   = 0;     // = diameter / 2（向下取整）
    qreal  falloffEdge = 0.0; // 过渡带宽度（归一化到半径），仅供调试查看

    bool isNull() const { return mask.isNull(); }
};

// 生成笔尖。
//
//   diameter —— 直径（像素），会被钳制到 1..2000
//   hardness —— 硬度 0..100。100 = 纯硬边，0 = 从中心就开始衰减
//
// ★ 即使 hardness = 100，也保留至少 1 像素的过渡带 ★
//   这是本函数里最重要的一条。完全硬边的圆在像素网格上会是明显的
//   阶梯锯齿，放大到 400% 时尤其难看；而且相邻落笔点之间会因为
//   "有的像素被覆盖、有的没有"产生毛刺。
//   留 1 像素过渡带后，边缘天然获得抗锯齿，视觉上平滑得多。
BrushTip makeBrushTip(int diameter, int hardness);

// ---------------------------------------------------------------------------
//  笔画补点
// ---------------------------------------------------------------------------
//  给定上一次落笔点与本次落笔点，返回两者之间应当落笔的位置序列。
//
//  ★ 为什么必须先补点，不能"鼠标到哪就在哪落一笔" ★
//
//    鼠标事件的采样频率远低于"一条平滑线所需的落笔密度"。
//    快速拖动时，两帧之间可能跨越上百像素，直接连线会变成一串
//    断开的圆点（俗称"算盘珠"）。补点把直线插值成间距 ≤ spacing
//    的密集落笔点，笔画才连续。
//
//  返回的点**不含 from，含 to** —— 因为 from 是上一段的终点，
//  在上一段里已经落过笔了。这个约定避免了线段衔接处的重复落笔
//  （重复落笔虽不会加深颜色，但会白白多算一次）。
//
//  spacing 会被钳制到 ≥ 0.5 像素，防止调用方传 0 导致死循环式补点。
QVector<QPointF> interpolateStamps(const QPointF &from, const QPointF &to,
                                   qreal spacing);

// ---------------------------------------------------------------------------
//  压入落笔点
// ---------------------------------------------------------------------------
//  把笔尖以 center 为中心压进累积蒙版。
//
//  ★ 合成方式是"取最大"，不是"累加"，也不是"覆盖" ★
//    · 取最大：同一笔内重叠区域的覆盖度不会超过单次落笔的强度
//              → 线条颜色均匀，这正是"不透明度"该有的语义
//    · 累加  ：重叠处会越涂越深（竹子状线条）
//    · 覆盖  ：后用的小笔刷会把先画的大笔刷痕迹抹掉
//
//  strength —— 单次落笔的强度（0..1），由流量/不透明度算出。
//              实际写入值是 tip 蒙版值 × strength。
//
//  ★ 本函数是本工程 engine 层**唯一**允许原地修改传入对象的函数 ★
//
//    原因是性能：累积蒙版是画布尺寸的（例如 4000×3000 = 12MB），
//    如果按"纯函数"风格每次落笔都返回一份新蒙版，画一笔要分配
//    上百次 12MB 内存 —— 内存带宽直接成为瓶颈，实测掉到个位数帧率。
//
//    这里的"副作用"是受控的：只写 mask，只往"更大"的方向改（取最大），
//    不会读取调用方的其他状态。把它看作"对一块临时缓冲的原地绘制"，
//    而不是"修改业务数据"，架构上仍然是干净的 ——
//    这个蒙版本就不是任何持久化数据，笔画结束即丢弃。
// ---------------------------------------------------------------------------
void stampTipInPlace(QImage &strokeMask, const BrushTip &tip,
                     const QPointF &center, qreal strength);

// 一个落笔点在蒙版坐标系里影响到的矩形（已含 1 像素抗锯齿余量）。
// 调用方用它累加出整笔的包围盒。
QRect stampBoundingRect(const BrushTip &tip, const QPointF &center);

// ---------------------------------------------------------------------------
//  合成到图层
// ---------------------------------------------------------------------------
//  把累积蒙版按颜色合成到图层上，返回**新的**图层位图（不改动入参）。
//
//  base          —— 整笔开始前的图层位图（必须是 ARGB32_Premultiplied）
//  strokeMask    —— 整笔累积覆盖度（Grayscale8，尺寸与 base 相同）
//  color         —— 画笔颜色；其 alpha 通道会与覆盖度相乘
//  erase         —— true 表示橡皮（擦除到透明），false 表示画笔
//  selectionMask —— 选区蒙版（Grayscale8，尺寸与 base 相同）。
//                   传空 QImage 表示"全选"（不做选区限制）。
//
//  ★ 两条关于预乘 alpha 的规则，这里与 Lut.cpp 的处理方式**相反** ★
//
//    引擎里有两个地方要处理预乘格式，但它们的正确做法截然不同：
//
//      · LUT 类调整（亮度/对比度/曲线…）→ 必须转成非预乘再查表
//        因为查表针对的是"颜色分量本身"，而预乘格式存的是
//        "颜色 × alpha"，直接查表会让半透明区域色偏。
//
//      · 合成类运算（本函数、Blend.cpp）→ **就在预乘空间做**
//        因为 source-over 的定义式在预乘空间里恰好是最简形式：
//            结果 = 源色×srcA + 目标×(1-srcA)
//        各通道独立、无需除法。转成非预乘反而要额外做乘除，
//        既慢又引入舍入误差。
//
//    本函数属于后者，因此全程在预乘空间运算，不做格式往返。
//
//  ★ 选区蒙版必须在"颜色预乘之前"乘进覆盖度 ★
//    如果先把颜色预乘好再乘选区，那么选区边缘的像素会得到
//    "颜色分量按完整 alpha 预乘、但 alpha 被选区的 0 乘掉"的结果 ——
//    即 rgba 里 rgb 不为 0 而 a 为 0。这种"有颜色但全透明"的像素
//    虽然不显示，却会在后续合成里因为舍入误差浮现出来，
//    表现为选区外缘一圈淡影。
QImage composeStroke(const QImage &base, const QImage &strokeMask,
                     const QColor &color, bool erase,
                     const QImage &selectionMask = QImage());

} // namespace zl
