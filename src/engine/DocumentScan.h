#pragma once

// ============================================================================
//  DocumentScan.h —— 文档扫描类处理（透视展平 + 白底黑字增强）
// ----------------------------------------------------------------------------
//  用途：手机拍的 A4 纸这类"斜着拍、光照不匀"的照片，先摆正再提成
//  "白纸黑字"，扫出来像扫描件。
//
//  分成两个互不依赖的纯函数组，理由与 Filters / Adjust 一致：
//    · unwarp()  —— 几何：把任意四边形映射成矩形。运算在**坐标**上，
//                   像素只是被重采样，不关心内容是什么。
//    · enhance() —— 色调：逐像素映射。完全不关心图像从哪来、摆没摆正。
//  两者不互相调用，用户可以只用其中一个（例如已经拍正了，只想去阴影）。
//
//  ★ 与 Adjust.h 的分界 ★
//    Adjust 里的色阶/曲线是**全局**映射：同一个输入值永远得到同一个输出。
//    而"去阴影"必须知道**局部背景有多亮** —— 纸在灯下是 240、在阴影里
//    只有 150，同一个 150 在亮处是文字、在暗处是纸。这不是一条 LUT 能表达的，
//    所以必须放在这里，用自己的"局部归一化"管线。
// ============================================================================

#include "core/ImageTypes.h"

#include <QImage>
#include <QPolygonF>
#include <QSize>

namespace zl {
namespace scan {

// ---------------------------------------------------------------------------
//  透视展平
// ---------------------------------------------------------------------------

// 把 quad 这四角围出的四边形，拉正成一张 outputSize 大小的矩形图。
//
//  quad 的顶点顺序**必须**是 左上 → 右上 → 右下 → 左下（顺时针）。
//  这个顺序不是随便定的：quadToQuad 是"点对点"映射，第 i 个源点对应
//  第 i 个目标点。顺序错了结果会是镜像或者交叉的，而且不一定报错。
//
//  失败返回空 QImage。会失败的情形：quad 不足 4 点、三点共线导致矩阵奇异
//  （用户把某个角拖到了对角线上）、outputSize 非法。
//
//  ★ 为什么不用 engine::transform::applyTransform ★
//    那个函数保持画布尺寸不变（图层内变换），而这里要**换画布尺寸** ——
//    展平的意义就是把歪斜的四边形铺满一张新的、正着的画布。
//    尺寸变化必须由 Document 层统一处理（所有图层 + 选区一起换），
//    所以那一步在 Document::unwarpPerspective 里，本函数只管出图。
//
//  ★ 插值质量的取舍 ★
//    QPainter 的平滑变换是双线性，不如本项目 Resample 里的 bicubic/Lanczos。
//    原因是透视映射的采样位置随像素变化，要自己做高阶采样就得把整个
//    变换写成逐像素循环，峰值内存与复杂度都会翻倍。双线性在"照片扫描"
//    这个场景下差异肉眼不可见（原始照片本身就有噪点），不值得。
//    method 只区分"要不要开平滑"：Nearest → 关，其余 → 开。
QImage unwarp(const QImage &src, const QPolygonF &quad, const QSize &outputSize,
              ResampleMethod method = ResampleMethod::Bicubic);

// 展平灰度蒙版（选区用）。内部把它当成"白色带 alpha"的图去变换，
// 回来后取 alpha 通道 —— 与图层走同一条变换，选区才不会偏。
// 蒙版格式必须是 Format_Grayscale8（Selection 的约定）。
QImage unwarpMask(const QImage &grayMask, const QPolygonF &quad,
                  const QSize &outputSize);

// 由四角估算展平后的像素尺寸：宽取上下两边较长者，高取左右两边较长者。
//
// ★ 为什么取"较长者"而不是平均 ★
//   A4 纸在照片里近大远小，远边短、近边长。取平均等于把所有边都缩到
//   比最长边还短，白丢分辨率；取长边最多也就是近边保持原样、远边被放大
//   （放大不会丢信息，只是插值）。扫描件宁可贵一点也不要糊。
//
// 返回的尺寸至少 1×1。四角退化成一个点时返回 (1,1)。
QSize suggestOutputSize(const QPolygonF &quad);

// 四角是否构成一个可用的四边形（不共线、面积为正、顺序合理）。
// 工具用它决定"要不要允许提交"，避免把奇异矩阵丢给 unwarp()。
bool isQuadUsable(const QPolygonF &quad);

// ---------------------------------------------------------------------------
//  文档增强参数
// ---------------------------------------------------------------------------

struct EnhanceParams
{
    // 去阴影（匀光）强度 [0,100]。
    //
    // 0 表示按整幅图的背景估计（几乎不平），100 表示用很小的窗口贴地估计
    // 背景 —— 连"手指投在纸上的影子"都能抹掉，但纸的纹理也会被一起抹平。
    // 50 是"能去掉台灯造成的半页阴影、又留住纸感"的位置。
    int shadow = 50;

    // 文字加深 [0,100]。抬黑场 + 加 gamma，把灰字压成黑字。
    int contrast = 50;

    // 纸张提白 [0,100]。压白场，让背景的浅灰变成纯白。
    int whiten = 50;

    // 转成黑白（灰度）。
    //
    // 默认关：很多人拍的是有红章、蓝签字的材料，去色等于把信息抹了。
    // 真需要"投屏/打印更清楚"时再勾。
    bool grayscale = false;

    bool operator==(const EnhanceParams &o) const
    {
        return shadow == o.shadow && contrast == o.contrast
            && whiten == o.whiten && grayscale == o.grayscale;
    }
    bool operator!=(const EnhanceParams &o) const { return !(*this == o); }
};

// 白底黑字增强。
//
// 管线（顺序不能换）：
//   ① 算亮度图
//   ② 用大窗口盒式模糊估计**局部背景亮度**（纸有多亮）
//   ③ 逐像素 归一化 n = 255·亮度/背景  —— 纸变成 255，文字留在低处，
//      光照不均在这一步被除掉（阴影区与亮区的纸都被拉到 255）
//   ④ 对 n 走一条"抬黑场 / 压白场 / gamma"的 LUT  → 文字更黑、纸更白
//
//  ★ 为什么②③要用"背景估计"而不是全局色阶 ★
//    全局色阶只能选一个黑场一个白场。半页阴影的照片，暗半页的纸只有 150，
//    若把白场定在 150 去救它，亮半页的纸（240）就全部爆掉；
//    反过来定在 240，暗半页永远是灰的。局部背景估计才有"各自归一"的能力。
//
//  ★ 性能：③④合成为一张 256×256 的二维表 ★
//    背景与像素都是 8 位，两者合起来只有 65536 种组合。烘一张
//    table[背景][像素] 之后，逐像素只剩一次查表 —— 没有除法、没有 pow。
//    1200 万像素约 3 次查表/像素，比逐像素浮点除法快一个数量级
//    （除法在 x86 上约 20~40 周期，查表是 1~4 周期）。
QImage enhance(const QImage &src, const EnhanceParams &params);

} // namespace scan
} // namespace zl
