#pragma once

// ============================================================================
//  Adjust.h —— 图像调整（基于 LUT 的逐像素映射）
// ----------------------------------------------------------------------------
//  本文件实现"输入值 → 输出值"类型的调整：亮度、对比度、色相、饱和度、
//  明度、色阶。全部走 LUT 烘焙 + 查表（见 Lut.h），性能远好于逐像素浮点运算。
//
//  关于预乘 alpha：本文件所有函数都通过 applyLuts() 应用结果，
//  而 applyLuts() 内部已经处理了"预乘 → 非预乘 → 查表 → 回预乘"的往返。
//  因此这里的实现**不需要**再关心预乘问题 —— 但前提是必须用 applyLuts，
//  如果哪天改成自己逐像素写，就必须重新处理一遍。
// ============================================================================

#include "core/ImageTypes.h"
#include "engine/Lut.h"

#include <QImage>

namespace zl {
namespace adjust {

// ---------------------------------------------------------------------------
//  亮度
// ---------------------------------------------------------------------------

// 参数范围 [-100, 100]，0 表示不变。
//
// 实现选择：使用**加法**而不是乘法。
//   加法：out = in + brightness/100    → 暗部提亮的效果均匀，容易压成纯黑/纯白
//   乘法：out = in * (1 + brightness) → 保持黑场不动，但高光容易过曝
//
// 专业编辑器（Photoshop 的"亮度/对比度"）用的是围绕中间调的曲线，
// 这里采用加法 + 轻微 S 形收敛的折中：在接近 0 和 1 的地方压缩变化率，
// 避免大面积"黑死"或"白死"。
CurveLut brightnessLut(int brightness);

// ---------------------------------------------------------------------------
//  对比度
// ---------------------------------------------------------------------------

// 参数范围 [-100, 100]，0 表示不变。
//
// 实现：围绕 0.5（中灰）做缩放：
//   out = (in - 0.5) * factor + 0.5
// 其中 factor 随 contrast 增大。
//
// 为什么围绕 0.5 而不是 0 或 1：围绕中灰缩放能保证中间调基本不动，
// 亮部更亮、暗部更暗，符合"对比度"的直觉。
// 若围绕 0 缩放，整张图会同时变亮，那就不是对比度而是亮度了。
CurveLut contrastLut(int contrast);

// ---------------------------------------------------------------------------
//  亮度 + 对比度联合
// ---------------------------------------------------------------------------
//  两个操作有先后顺序之分。分开应用等于：out = contrast(brightness(in))
//  合并成一条 LUT 只需逐像素查一次表，比查两次快一倍。
//
//  顺序很重要且必须与界面上的预览一致，否则用户会看到"确定后的结果与
//  预览不同"这种诡异的 bug。约定：**先亮度，后对比度**。
CurveLut brightnessContrastLut(int brightness, int contrast);

// ---------------------------------------------------------------------------
//  饱和度
// ---------------------------------------------------------------------------

// 参数范围 [-100, 100]，0 表示不变，-100 为完全去色。
//
// 注意：饱和度是**三通道相关**的运算，不能像亮度那样对每个通道独立做
// 一条 LUT。做法是先算好一张"灰度映射表"，然后逐像素按饱和度系数在
// 原色与灰度之间插值：
//     out = gray + (in - gray) * saturation
// 其中 gray 由亮度公式（0.299R + 0.587G + 0.114B）算出。
//
// 因此本函数返回的不是单表，而是需要用 applySaturation() 来应用。
// （保留独立函数而不是塞进 CurvesSettings，是因为它在语义上属于调整而非曲线。）
QImage applySaturation(const QImage &src, int saturation);

// ---------------------------------------------------------------------------
//  色相
// ---------------------------------------------------------------------------

// 参数范围 [-180, 180]，0 表示不变。单位为度。
//
// 色相旋转必须在 HSL/HSV 空间做，同样是三通道相关运算，无法用单表实现。
//
// 实现优化：色相旋转相当于在 RGB 立方体里绕灰度轴旋转，可以用一个
// 3×3 矩阵表示（不需要真的转 HSL）。这个矩阵法的好处是逐像素只需
// 9 次乘加，比来回转 HSL 快很多，而且没有 HSL 转换中的分支。
QImage applyHue(const QImage &src, int hueShift);

// ---------------------------------------------------------------------------
//  明度（Lightness）
// ---------------------------------------------------------------------------

// 参数范围 [-100, 100]，0 表示不变。
//
// 与"亮度"的区别：
//   亮度（Brightness）—— 加法调整，会影响饱和度感知（提亮会让颜色变淡）
//   明度（Lightness）—— 按比例调整，更接近"曝光"的概念
// 界面上两者都提供，因为用户对"该调哪个"的感受因人而异。
QImage applyLightness(const QImage &src, int lightness);

// ---------------------------------------------------------------------------
//  色相 / 饱和度 / 明度 联合
// ---------------------------------------------------------------------------
//  三者一起应用比分别应用三次快得多，且能保证结果的一致性
//  （分别应用时每次都要做一遍格式转换与遍历）。
//
//  运算顺序约定：**先色相，再饱和度，最后明度**。
//  这个顺序与 Photoshop 的"色相/饱和度"对话框一致。
QImage applyHueSaturationLightness(const QImage &src,
                                    int hueShift, int saturation, int lightness);

// ---------------------------------------------------------------------------
//  色阶（Levels）
// ---------------------------------------------------------------------------

// 色阶参数：输入黑场 / 白场 → 输出范围，以及中间调 gamma。
struct LevelsParams
{
    int   inBlack  = 0;      // 输入黑场，0~255
    int   inWhite  = 255;    // 输入白场，0~255
    qreal gamma    = 1.0;    // 中间调 gamma，0.1~10，>1 变亮
    int   outBlack = 0;      // 输出黑场
    int   outWhite = 255;    // 输出白场
};

// 色阶是曲线的一个特例（四点定形的曲线），但它是独立的高频功能，
// 因此单独提供入口并带参数校验。
CurveLut levelsLut(const LevelsParams &params);

// ---------------------------------------------------------------------------
//  自动色阶 / 自动对比度
// ---------------------------------------------------------------------------

// 自动色阶：统计直方图，把 0.1% 与 99.9% 分位处作为黑白场。
//
//  为什么要截掉两端各 0.1%：图像里常有极少数纯黑或纯白的噪点，
//  如果按"最小值和最大值"来定黑白场，一个噪点就能让整张图几乎不变。
//  用分位数能忽略这些异常值。
LevelsParams computeAutoLevels(const QImage &src,
                               qreal clipPercent = 0.1);

} // namespace adjust
} // namespace zl
