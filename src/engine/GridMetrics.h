#pragma once

// ============================================================================
//  GridMetrics.h —— 网格吸附的数学（纯函数）
// ----------------------------------------------------------------------------
//  一句话：给定"网格间距 + 一个坐标（或一个矩形）+ 容差"，算出**吸附到哪**。
//  与 engine 其他文件同规矩：不建控件、不碰 QPainter、不碰 Document，
//  只看输入出输出，**可以被离线自检直接断言**。
//
//  ★★ 为什么吸附必须是纯函数、不能写在工具里 ★★
//
//    "吸附"是"看起来很主观、其实完全可判定"的东西：给定间距与坐标，
//    结果唯一。写进 MoveTool / SelectionTool 的 mouseMove 里，唯一的
//    验收方式就是"拖着看"——而那正是我们不许出现的验收方式
//    （见 docs/实现铁律.md 第九章 / 三类静默失效之"自绘控件"）。
//
//    抽成纯函数之后，"容差内吸、容差外不吸""矩形按最近那条边整体平移
//    而不是缩放""间距非法时原样返回"这些断言都能逐条写死，改坏立刻变红。
//
//  ★★ 为什么容差用"屏幕像素"、由调用方折算成图像像素 ★★
//
//    与标尺刻度同一条纪律（见 engine/RulerMetrics.h）："离得近不近"只跟
//    屏幕上看起来怎么样有关。若容差写成固定的图像像素，缩到 10% 时
//    8 图像像素 ≈ 0.8 屏幕像素 —— 用户根本感受不到吸附；放大到 800% 时
//    8 图像像素 ≈ 64 屏幕像素 —— 鼠标离得老远就被"吸走"，像失控。
//    所以容差由调用方按**当前缩放**折算后传进来（见 toleranceInImage）。
// ============================================================================

#include <QtGlobal>
#include <QPoint>
#include <QPointF>
#include <QRect>

namespace zl {
namespace gridmetrics {

// ---------------------------------------------------------------------------
//  生效判据
// ---------------------------------------------------------------------------
//  网格是否"可用"。间距 <= 0 表示网格关闭或配置非法 →
//  所有吸附函数一律**原样返回**（不吸附）。
//
//  ★ 为什么把判据收敛到一个函数里 ★
//    三个吸附函数都要问同一句话。分散写会有一个漏掉 —— 而"漏掉"的
//    表现是除零（间距 0 → v/0 = inf → 取整后是垃圾值），画面乱跳却
//    不报任何错。收敛到一处就只有这一处要保证正确。
inline bool isUsable(int gridSize)
{
    return gridSize > 0;
}

// 把"屏幕像素容差"折算成"图像像素容差"。
//
//   screenPx —— 屏幕上允许多大的偏移还算"临近"（例如 8）
//   zoom     —— 画布当前的"图像像素 → 屏幕像素"倍率
//
//   zoom <= 0（或 NaN）→ 按 1.0 处理。
//     回落成 0 会让容差变成 0 = 永远不吸附，表现是"这个功能坏了"，
//     而这比"用 1:1 的容差不精确"严重得多。空/非法 zoom 在任何
//     真实路径上都不该出现，这里只是不让它变成静默故障。
inline qreal toleranceInImage(qreal screenPx, qreal zoom)
{
    const qreal z = (zoom > 0.0) ? zoom : 1.0;
    return screenPx / z;
}

// 离 v 最近的网格线坐标（v 可以是任意实数）。
// gridSize <= 0 → 原样返回 v。
qreal nearestLine(qreal v, int gridSize);

// 一维吸附：v 离最近网格线的距离 <= tolPx 时吸上去，否则**原样返回**。
//
//   ★ "原样返回"而不是"取整"★
//     网格吸附的语义是"帮你对齐"，不是"限制你只能落在网格上"。
//     超出容差还强行取整，用户就再也无法把东西放在两条线之间了。
//
//   tolPx 为**图像像素**（由调用方用 toleranceInImage 折算）。
//   tolPx < 0 视为 0（只有恰好在网格上才"吸"，等价于不动）。
qreal snapValue(qreal v, int gridSize, qreal tolPx);

// 二维点吸附：两轴各自独立按 snapValue 处理。
QPointF snapPoint(qreal x, qreal y, int gridSize, qreal tolPx);

// ---------------------------------------------------------------------------
//  矩形吸附：返回"整体平移量"（不是新矩形）
// ---------------------------------------------------------------------------
//  返回把一个矩形**整体平移**到网格所需的 (dx, dy)，形状与大小完全不变。
//
//  ★★ 为什么是"整体平移"而不是"把四条边各自吸到网格" ★★
//
//    后者会把矩形**改形**（宽高被撑到网格倍数）—— 那是"缩放"，
//    不是"对齐"。用户拖着一个 37×53 的图层，想要的是"让它对齐到网格线"，
//    不是"把它变成 64×64"。所以这里只算一个平移量，
//    而且**每轴只挑一条边**：挑左右边里离网格更近的那条来决定 dx。
//
//  例：left=30、right=67、g=64。left 离 64 差 34，right 离 64 差 3 →
//      挑右边 → dx = +(-3) → 平移后 left=27、right=64。右边贴合，
//      宽度仍是 37。
//
//  两条边都超出容差 → 该轴平移量为 0（"爱放哪放哪"）。
//  空矩形 / 间距非法 → 返回 (0, 0)。
QPoint snapOffsetForRect(const QRect &rect, int gridSize, qreal tolPx);

} // namespace gridmetrics
} // namespace zl