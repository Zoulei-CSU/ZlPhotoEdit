#pragma once

// ============================================================================
//  Lut.h —— 查找表（Look-Up Table）调整流水线
// ----------------------------------------------------------------------------
//  为什么需要 LUT：
//    亮度、对比度、曲线、色阶这类"逐像素映射"的调整，本质都是
//      output = f(input)
//    其中 f 对每个通道都是同一个函数。8 位图像的输入只有 256 种可能！
//    与其对每个像素做浮点运算，不如先把 f 在 256 个输入上算好存成表，
//    然后逐像素查表。4000×3000 的图像有 1200 万像素，查表比算浮点大约快
//    5~10 倍。
//
//  ★ 关键陷阱：预乘 alpha 格式下的查表色偏 ★
//
//    这是本项目最容易搞错、症状最隐蔽的地方，必须理解透彻：
//
//    图层位图使用 Format_ARGB32_Premultiplied，它的 R/G/B 分量**已经乘过
//    alpha**。假设一个纯白色、50% 透明的像素：
//      非预乘空间：(255, 255, 255, 128)
//      预乘空间：  (128, 128, 128, 128)   ← 255 * 128/255 = 128
//
//    现在有一条把中间调调亮的曲线。它期望的输入是"255"，实际拿到的却是
//    "128"。128 和 255 在曲线上处于完全不同的位置，于是半透明区域被错误地
//    当成暗部处理，提亮后颜色明显不对。
//
//    正确做法（本文件的做法）：
//      1. 取出预乘像素，转成非预乘（除以 alpha）
//      2. 在非预乘空间查表
//      3. 结果乘回 alpha，转回预乘
//
//    例外（务必区分）：
//      · 混合模式（Blend.cpp）—— 运算定义在预乘空间，**不做**这个往返
//      · 重采样（Resample.cpp）—— 线性插值在预乘空间做才正确，**不做**往返
//    只有"按原始 RGB 值查表"的调整类运算需要往返。这个区别写在这里，
//    免得实现时凭直觉统一处理，那必然出错。
// ============================================================================

#include <QImage>
#include <array>

namespace zl {

// ---------------------------------------------------------------------------
//  单通道 LUT
// ---------------------------------------------------------------------------
//  用 std::array<quint8, 256> 而不是 std::vector：固定大小、栈上分配、
//  无堆开销，而且能直接看出"这就是 256 项"。
// ---------------------------------------------------------------------------
using CurveLut = std::array<quint8, 256>;

// 生成恒等表（output == input），作为所有调整的起点
CurveLut identityLut();

// 用函数对象填充 LUT。fn 接受 [0,1] 的归一化输入，返回 [0,1] 的输出。
// 用模板是为了避免 std::function 的间接调用开销 —— 这个函数在拖动滑块时
// 会被高频调用（每次滑块变化都要重新烘焙），开销值得省。
template <typename Fn>
CurveLut bakeLutFromFn(Fn fn)
{
    CurveLut lut{};
    for (int i = 0; i < 256; ++i) {
        const qreal input = i / 255.0;
        const qreal output = fn(input);
        // 钳制到合法范围并四舍五入。不钳制的话，过冲的曲线值会溢出成
        // 完全相反的颜色（例如 1.2 → 306 → 截断为 50，从白翻到黑）。
        const int v = int(qRound(qBound(0.0, output, 1.0) * 255.0));
        lut[size_t(i)] = quint8(qBound(0, v, 255));
    }
    return lut;
}

// ---------------------------------------------------------------------------
//  三通道 LUT（RGB 各一份，可不同）
// ---------------------------------------------------------------------------
struct ChannelLuts
{
    CurveLut r = identityLut();
    CurveLut g = identityLut();
    CurveLut b = identityLut();

    // 三个通道是否完全相同。若相同，可以走"单表快路径"，
    // 省掉两次内存访问 —— 这是绝大多数调色场景（RGB 通道共用一条曲线）。
    bool isMonochrome() const { return r == g && g == b; }
};

// ---------------------------------------------------------------------------
//  应用 LUT 到图像
// ---------------------------------------------------------------------------

// 把三通道 LUT 应用到图像上，返回新图像。
//
// 内部自动处理上述的"预乘往返"：
//   · 输入是 ARGB32_Premultiplied 时，逐像素做 预乘 → 非预乘 → 查表 → 预乘
//   · 输入是 ARGB32 时直接查表
//   · 其余格式先转 ARGB32 再处理
//
// 返回格式与输入保持一致，调用方无需关心。
QImage applyLuts(const QImage &src, const ChannelLuts &luts);

// 便捷版本：单条 LUT 同时作用于 RGB 三通道（最常见的用法，
// 例如"亮度"、"对比度"、RGB 主曲线）
QImage applyLutRgb(const QImage &src, const CurveLut &lut);

// ---------------------------------------------------------------------------
//  通道叠乘
// ---------------------------------------------------------------------------
//  曲线对话框里，RGB 主曲线与单通道曲线是**叠乘**关系，不是覆盖：
//      final(x) = curveBlue(curveGreen(curveRed(curveRgb(x))))
//
//  也就是说，一个像素要依次穿过四条曲线。这个顺序（RGB 主曲线在最内层）
//  与 Photoshop 一致。
//
//  实现上不必对每个像素做四次查表 —— 只要把四条曲线**预先合成一条**，
//  逐像素只查一次表。合成一次 256 项的成本可以忽略。
CurveLut composeLut(const CurveLut &inner, const CurveLut &outer);

} // namespace zl
