#pragma once

// ============================================================================
//  Outline.h —— 选区轮廓（灰度蒙版 → 边界线段路径）
// ----------------------------------------------------------------------------
//  为什么这段算法要从 ui/CanvasView 搬到 engine：
//
//  ① 它是**纯像素算法**：输入一张 Grayscale8 蒙版 + 一个包围盒提示，
//     输出一条 QPainterPath。没有状态、没有副作用、不碰控件 ——
//     正是 engine 层该放的东西（与 Shape / Fill / RulerMetrics 同一类）。
//
//  ② ★ 它是"自绘管线"，而自绘管线必须有"量它画出来的像素"的断言 ★
//     （见 docs/实现铁律.md §8.3 与 §11.6）。留在 CanvasView 的私有成员函数里
//     时，这段一百行的扫描代码**在整工程里没有任何一条断言碰过它** ——
//     它错了的表现是"蚂蚁线跑到脸上 / 缺一段 / 整圈外扩"，
//     不崩溃、不报错，属于最难发现的一类。搬到 engine 之后
//     tests/perf_test.cpp 可以直接调它做像素级断言与计时。
//
//  ③ ★ 性能：让"可测量"成为可能 ★
//     选区轮廓原先在**每一个画笔事件**里都被整块重扫
//     （见 docs/性能优化评估.md §1.3）。"先量后改"的前提是这段算法
//     能被单独调用与计时 —— 所以先搬出来，再决定怎么改。
// ============================================================================

#include <QImage>
#include <QPainterPath>
#include <QRect>

namespace zl {
namespace outline {

// 把选区灰度蒙版提取成"边界线段路径"（图像坐标）。
//
// 参数：
//   grayMask  —— Format_Grayscale8，尺寸与画布一致。0 = 未选中。
//   boundsHint —— 已知的"非零区域"包围盒（即 Selection::bounds()）。
//                 ★ 这是本函数唯一重要的优化 ★
//                 包围盒之外全是 0，那里的"边界"只可能是画布边缘 ——
//                 而画布边缘本来就不需要画蚂蚁线。
//                 用户只框了一个小图标时，扫描量从"整张图"降到那个小方块；
//                 全选时它退化成"整张图"（此时本来就没有别的办法）。
//                 ★ 传空矩形 = 不知道 → 退化成扫整张蒙版 ★（慢，但结果正确）
//
//                 ★★ 契约：hint 必须是**真的**包住全部非零像素 ★★
//                 扫描范围之外一律按"未选中"（0）处理 —— 这本是为画布边缘
//                 准备的规则，但当 hint 给小时它会反过来咬人：
//                 hint 的四条边会被当成"选中/未选中的交界"，
//                 于是**凭空长出一圈矩形轮廓**。
//                   · 真实调用点（CanvasView 传 Selection::bounds()）是安全的 ——
//                     包围盒按定义就包住了全部非零像素；
//                   · 但谁要是为了"更快"随手传一个估出来的小矩形，
//                     就会得到一条不属于任何选区的假蚂蚁线，而且**不报错**。
//                   perf 自检 8.2 有一条断言把这个行为钉住（故意传小 hint）。
//   threshold —— 二值化阈值，默认 128。
//                抗锯齿与羽化会产生 1~254 的过渡值。取 128 让边界落在
//                过渡带正中，视觉上最稳定；取 1 蚂蚁线会跑到羽化最外圈，
//                取 255 则跑到内圈。
//
// 返回：一条由**线段**构成的路径（只含 moveTo / lineTo，没有曲线）。
//
// ★ 为什么必须"合并成连续段"，而不是每个像素加一小段 ★
//   ① 虚线相位：Qt 的虚线图案是按子路径分别起算的。每条子路径只有 1 像素长
//      时，虚线会在每个像素处重新开始 —— 画出来看着像一条实线，
//      完全没有"蚂蚁"的效果。
//   ② 性能：一条 1000 像素的边若拆成 1000 个子路径，
//      路径构建与描边都要慢一个数量级。
//
// ★ 本函数只管"轮廓在哪"，不管"怎么画" ★
//   线宽 / 颜色 / 虚线相位属于呈现，见 tools/MarchingAnts.h。
//   拆开的理由是：同一套观感要同时用在"已确定的选区"（CanvasView）
//   与"正在拖出来的选区预览"（SelectionTool）上，两处各写一份必然漂移。
QPainterPath maskOutline(const QImage &grayMask,
                         const QRect &boundsHint = QRect(),
                         int threshold = 128);

} // namespace outline
} // namespace zl
