#pragma once

// ============================================================================
//  MarchingAnts.h —— 选区边界"蚂蚁线"的统一画法
// ----------------------------------------------------------------------------
//  为什么单独放一个文件：
//    这条边界要在两个地方画 ——
//      · CanvasView      画"已经存在的选区"（第 9 步呈现）
//      · SelectionTool   画"正在拖出来的新选区"（工具叠加层）
//    两处必须**长得一模一样**，否则用户松手瞬间会看到线条风格突变
//    （虚线段长度、颜色、粗细全变），像是程序抽了一下。
//    与其在两处各写一份并靠注释提醒"改这里要同步改那里"，
//    不如只留一份实现。
//
//  ★ 分层位置说明 ★
//    放在 tools/ 而不是 ui/：tools 层不允许 include ui 层的任何东西，
//    但 ui 层可以 include tools 层（依赖方向 ui → tools）。
//    放在这里两种调用方都能用；放在 ui/ 则工具层无法复用。
//    本文件只依赖 QtGui（QPainter / QPainterPath），不含 QtWidgets。
// ============================================================================

class QPainter;
class QPainterPath;

namespace zl {

// 用"黑底 + 白虚线"把一条路径画成蚂蚁线。
//
// ★ 为什么要画两层 ★
//   单色的虚线在照片上必然有看不清的地方：
//     · 白色虚线在雪景、白墙、过曝区域上完全消失
//     · 黑色虚线在夜景、深色头发、阴影里完全消失
//   先铺一条实心黑线打底，再在上面盖白色虚线，露出来的就是
//   "黑段与白段交替" —— 无论底下是什么颜色，总有一段是可见的。
//   这是所有图像编辑器都采用的做法，不是随意选的配色。
//
// ★ dashPhase 的作用 ★
//   虚线的起始相位。调用方每次重绘时把它加 1，虚线段就会沿路径
//   "流动"起来 —— 这正是"蚂蚁线"这个叫法的来源，也是它最重要的
//   功能语义：让用户一眼分辨出"这是选区边界（会动）"，
//   而不是"图像上本来就有的一条线（不会动）"。
//
// ★ 坐标系由调用方决定，本函数不碰 painter 的变换与裁剪 ★
//   两种调用场景都能正确工作：
//     · 图像坐标系（painter 已 setTransform）—— 此时路径是图像坐标，
//       绘制结果随缩放平移一起跟随，正是选区该有的行为
//     · 控件坐标系（painter 未变换）—— 直接按像素画
//   之所以两种都正确，是因为本函数统一使用 **cosmetic 画笔**：
//   它的线宽定义在设备空间，恒为 1 像素，与 painter 的变换无关。
//   否则放大到 800% 时，蚂蚁线会变成一条 8 像素宽的带子。
//
//   本函数会设置画笔与画刷，但**不保存也不恢复** painter 状态 ——
//   调用方若在意，请自行 save()/restore() 包起来。
void drawMarchingAnts(QPainter &painter, const QPainterPath &path, int dashPhase);

} // namespace zl
