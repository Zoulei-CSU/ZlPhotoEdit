#include "tools/ToolEvent.h"

// ============================================================================
//  ToolEvent.cpp —— 目前没有需要单独编译的实现
// ----------------------------------------------------------------------------
//  ToolEvent / ToolModifiers / ToolResult 都是头文件内联的轻量值类型，
//  这里留一个空的翻译单元，理由有二：
//
//    1. **qmake 与 CMake 的工程文件里已经声明了它**。
//       删掉会导致工程文件与实际文件不一致 —— 这种不一致往往在
//       "换一台机器重新构建"时才暴露出来，排查成本很高。
//
//    2. **将来加实现时不需要改工程文件**。
//       例如要做"把 ToolEvent 序列化成日志用于回放测试"，
//       或者为其增加一个 toString() 调试输出，直接写在这里就行。
//
//  注意：本文件必须存在且参与编译，否则 MSVC 会报 LNK1181（找不到 .obj）。
// ============================================================================

namespace zl {
namespace tools_detail {

// 一个内部链接的常量，保证本翻译单元不会因为"没有任何符号"而被
// 某些工具链判定为空目标文件（虽然 MSVC 不会，但保持这个习惯无害）。
constexpr int kToolEventTranslationUnitMarker = 1;

} // namespace tools_detail
} // namespace zl
